def parse_reading_sections(text: str) -> dict[str, str]:
    """
    将 LLM 输出按章节拆分为结构化数据，供前端分块渲染。

    Returns:
        dict with keys: overview, judgment, classics, kb_reference, analysis, advice, extra, footer
    """
    import re
    
    sections = {
        "overview": "",
        "judgment": "",
        "classics": "",
        "kb_reference": "",
        "analysis": "",
        "advice": "",
        "extra": "",
        "footer": "",
    }
    
    patterns = {
        "overview": r"【卦象总览】\s*\n(.*?)(?=【核心判断】|$)",
        "judgment": r"【核心判断】\s*\n(.*?)(?=【古籍依据】|$)",
        "classics": r"【古籍依据】\s*\n(.*?)(?=【知识库参照】|$)",
        "kb_reference": r"【知识库参照】\s*\n(.*?)(?=【详细分析】|【给你的建议】|$)",
        "analysis": r"【详细分析】\s*\n(.*?)(?=【给你的建议】|$)",
        "advice": r"【给你的建议】\s*\n(.*?)(?=【关于此卦】|---|$)",
        "extra": r"【关于此卦】\s*\n(.*?)(?=---|$)",
        "footer": r"---(.*?)$",
    }
    
    for key, pattern in patterns.items():
        match = re.search(pattern, text, re.DOTALL)
        if match:
            sections[key] = match.group(1).strip()
    
    return sections


